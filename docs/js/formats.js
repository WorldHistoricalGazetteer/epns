const AAT = 'http://vocab.getty.edu/aat/';
const GEONAMES = (id) => `https://sws.geonames.org/${id}/`;
const LICENCE_TEXT = 'Digitisation of English Placenames MADS data is licensed to Jisc by the English Place Names Society and released under a Creative Commons Attribution-NonCommercial 4.0 International License.';

