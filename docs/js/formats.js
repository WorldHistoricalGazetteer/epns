/* formats.js — one DEEP record as PLATO (place-centric SpatialEntity), as an LPF v1.3 Feature with
 * its losses named, and as regenerated MADS XML.
 *
 * THIS IS A PORT OF process/export_plato.py AND MUST STAY EQUAL TO IT. The downloads are made by the
 * Python; the record panel is made by this file; a reader comparing the two must see the same
 * object. tools/pages/shot.py loads docs/data/plato-sample.json (written by the Python with
 * `--sample`) and requires deep equality with what this file produces for the same records, so a
 * drift in either direction is a failing check rather than a silent divergence. When the Python
 * changes, change this, regenerate the sample, and let the check say whether they agree.
 *
 * Identifiers: nothing is minted. The entity's @id is the URI DEEP published for the record
 * (dead since the domain changed hands); names carry DEEP's URIs for the forms; attestations are
 * fragments on the record URI. The PLATO commit the mapping targets is not hard-coded here: the
 * panel reads it from plato-sample.json, which the Python stamped.
 */

